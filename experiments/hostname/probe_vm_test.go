type fixture struct {
	t            *testing.T
	stdin        io.WriteCloser
	stdout       *bufio.Scanner
	listener     *net.TCPListener
	probe        *probe
	pid          uint32
	observations string

	object, cgroup, sslPath, cryptoPath string
}

type connection struct {
	slot      int
	cookie    uint64
	fd        int
	localPort int
	server    *net.TCPConn
}

func newFixture(t *testing.T, network string) *fixture {
	t.Helper()
	return newFixtureMode(t, network, false)
}

func newFixtureMode(t *testing.T, network string, liveSend bool) *fixture {
	t.Helper()
	return newFixtureObject(t, network, liveSend, "")
}

func newFixtureObject(t *testing.T, network string, liveSend bool, override string) *fixture {
	t.Helper()
	object, client := os.Getenv("HOSTNAME_VM_OBJECT"), os.Getenv("HOSTNAME_VM_CLIENT")
	if liveSend {
		object = os.Getenv("HOSTNAME_VM_SEND_OBJECT")
	}
	if override != "" {
		object = override
	}
	if object == "" || client == "" {
		t.Skip("set HOSTNAME_VM_OBJECT and HOSTNAME_VM_CLIENT in the test VM")
	}
	if os.Geteuid() != 0 {
		t.Fatal("requires root in the test VM")
	}
	self, err := os.Readlink("/proc/self/ns/net")
	if err != nil {
		t.Fatal(err)
	}
	init, err := os.Readlink("/proc/1/ns/net")
	if err != nil || init == self {
		t.Fatal("run under unshare --net with loopback up")
	}
	addr, family := "127.0.0.1", "4"
	if network == "tcp6" {
		addr, family = "::1", "6"
	}
	l, err := net.ListenTCP(network, &net.TCPAddr{IP: net.ParseIP(addr)})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { l.Close() })
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	t.Cleanup(cancel)
	cmd := exec.CommandContext(ctx, client, family, addr, strconv.Itoa(l.Addr().(*net.TCPAddr).Port))
	in, err := cmd.StdinPipe()
	if err != nil {
		t.Fatal(err)
	}
	out, err := cmd.StdoutPipe()
	if err != nil {
		t.Fatal(err)
	}
	cmd.Stderr = os.Stderr
	if err := cmd.Start(); err != nil {
		t.Fatal(err)
	}
	// Children are always reaped, including failures during attachment.
	var finishOnce sync.Once
	finish := func() { finishOnce.Do(func() { in.Close(); cancel(); cmd.Wait() }) }
	t.Cleanup(finish)
	f := &fixture{t: t, stdin: in, stdout: bufio.NewScanner(out), listener: l, pid: uint32(cmd.Process.Pid), observations: "snapshots"}
	if liveSend {
		f.observations = "send_snapshots"
	}
	if line := f.read(); line != "ready" {
		t.Fatalf("client: %s", line)
	}
	cgroup := filepath.Join("/sys/fs/cgroup", fmt.Sprintf("hostname-experiment-%d", cmd.Process.Pid))
	if err := os.Mkdir(cgroup, 0700); err != nil {
		t.Fatal(err)
	}
	// Registered before the child-reap cleanup would remove too early; kill
	// and reap here first, then remove this task's cgroup only.
	t.Cleanup(func() {
		finish()
		if err := os.Remove(cgroup); err != nil {
			t.Error(err)
		}
	})
	if err := os.WriteFile(filepath.Join(cgroup, "cgroup.procs"), []byte(strconv.Itoa(cmd.Process.Pid)), 0600); err != nil {
		t.Fatal(err)
	}
	ssl, err := filepath.EvalSymlinks("/usr/lib64/glibc-hwcaps/x86-64-v3/libssl.so.3")
	if err != nil {
		t.Fatal(err)
	}
	crypto, err := filepath.EvalSymlinks("/usr/lib64/glibc-hwcaps/x86-64-v3/libcrypto.so.3")
	if err != nil {
		t.Fatal(err)
	}
	f.probe, err = attachMode(object, cgroup, ssl, crypto, cmd.Process.Pid, liveSend)
	if err != nil {
		t.Fatal(err)
	}
	f.object, f.cgroup, f.sslPath, f.cryptoPath = object, cgroup, ssl, crypto
	t.Cleanup(f.probe.close)
	return f
}

func (f *fixture) read() string {
	f.t.Helper()
	if !f.stdout.Scan() {
		f.t.Fatalf("client closed output: %v", f.stdout.Err())
	}
	return f.stdout.Text()
}
func (f *fixture) command(format string, args ...interface{}) string {
	f.t.Helper()
	if _, err := fmt.Fprintf(f.stdin, format+"\n", args...); err != nil {
		f.t.Fatal(err)
	}
	return f.read()
}
func (f *fixture) socket(line string) connection {
	f.t.Helper()
	var c connection
	if n, err := fmt.Sscanf(line, "socket %d %d %d %d", &c.slot, &c.cookie, &c.fd, &c.localPort); err != nil || n != 4 || c.cookie == 0 {
		f.t.Fatalf("socket response %q: %v", line, err)
	}
	var seeded uint64
	if err := f.probe.collection.Maps["last_seeded"].Lookup(uint32(0), &seeded); err != nil || seeded != c.cookie {
		f.t.Fatalf("cookie %d was not generated by sock_create: seeded %d, error %v", c.cookie, seeded, err)
	}
	return c
}
func (f *fixture) accepted(line string) connection {
	f.t.Helper()
	c := f.socket(line)
	f.listener.SetDeadline(time.Now().Add(5 * time.Second))
	var err error
	c.server, err = f.listener.AcceptTCP()
	if err != nil {
		f.t.Fatal(err)
	}
	f.t.Cleanup(func() { c.server.Close() })
	return c
}
func (f *fixture) open(name, order, mode string) connection {
	f.t.Helper()
	c := f.accepted(f.command("open %s %s %s", name, order, mode))
	f.absent(c)
	return c
}
func (f *fixture) absent(c connection) {
	f.t.Helper()
	if o, err := lookupPublished[observation](f.probe, f.observations, c.cookie); !errors.Is(err, ebpf.ErrKeyNotExist) && !errors.Is(err, errPublicationBusy) && !errors.Is(err, errPublicationChanged) {
		f.t.Fatalf("expected unknown cookie %d; got %+v, %v", c.cookie, o, err)
	}
}
func (f *fixture) lookup(c connection) observation {
	f.t.Helper()
	o, err := stableLookup[observation](f, f.observations, c.cookie)
	if err != nil {
		f.t.Fatal(err)
	}
	if o.Cookie != c.cookie || o.TGID != f.pid || o.FD != int32(c.fd) || o.BootNS == 0 {
		f.t.Fatalf("incorrect socket identity: %+v, expected %+v PID %d", o, c, f.pid)
	}
	return o
}

// A test may wait briefly for unrelated ACK publication to finish. The reader
// itself never retries or accepts a busy/changed control word.
func stableLookup[T sendRecord](f *fixture, name string, key interface{}) (T, error) {
	deadline := time.Now().Add(100 * time.Millisecond)
	for {
		value, err := lookupPublished[T](f.probe, name, key)
		if (!errors.Is(err, errPublicationBusy) && !errors.Is(err, errPublicationChanged)) || time.Now().After(deadline) {
			return value, err
		}
		time.Sleep(time.Millisecond)
	}
}
func wireName(t *testing.T, c connection) string {
	t.Helper()
	var name string
	c.server.SetDeadline(time.Now().Add(3 * time.Second))
	server := tls.Server(c.server, &tls.Config{GetConfigForClient: func(hello *tls.ClientHelloInfo) (*tls.Config, error) {
		name = hello.ServerName
		return nil, errors.New("test peer stops after reading ClientHello")
	}})
	server.Handshake()
	if name == "" {
		t.Fatal("no named TLS ClientHello arrived")
	}
	return name
}
func bootNS(t *testing.T) uint64 {
	t.Helper()
	var ts unix.Timespec
	if err := unix.ClockGettime(unix.CLOCK_BOOTTIME, &ts); err != nil {
		t.Fatal(err)
	}
	return uint64(ts.Nano())
}

func TestVMSnapshot(t *testing.T) {
	for _, network := range []string{"tcp4", "tcp6"} {
		for _, order := range []string{"name-first", "fd-first"} {
			for _, mode := range []string{"fd", "dup"} {
				t.Run(network+"/"+order+"/"+mode, func(t *testing.T) {
					f := newFixture(t, network)
					c := f.open("Example.TEST", order, mode)
					start := bootNS(t)
					f.command("thread %d", c.slot)
					o := f.lookup(c)
					name, err := o.hostname()
					if err != nil || name != "example.test" {
						t.Fatalf("name %q: %v", name, err)
					}
					if got := wireName(t, c); got != "Example.TEST" {
						t.Fatalf("wire name %s", got)
					}
					if o.BootNS < start || o.BootNS > bootNS(t) {
						t.Fatal("invalid publication time")
					}
				})
			}
		}
	}
}

func TestVMConcurrentAndReuse(t *testing.T) {
	f := newFixture(t, "tcp4")
	var live []connection
	for i := 0; i < 24; i++ {
		live = append(live, f.open(fmt.Sprintf("live-%d.test", i), "name-first", "fd"))
	}
	for i := len(live) - 1; i >= 0; i-- {
		c := live[i]
		f.command("handshake %d", c.slot)
		name, err := f.lookup(c).hostname()
		if want := fmt.Sprintf("live-%d.test", i); err != nil || name != want || wireName(t, c) != want {
			t.Fatalf("slot %d got %q: %v", i, name, err)
		}
	}
	for _, c := range live {
		f.command("close %d", c.slot)
	}
	var previousFD int
	for i := 0; i < 64; i++ {
		want := fmt.Sprintf("reuse-%d.test", i)
		c := f.open(want, "fd-first", "fd")
		if i > 0 && c.fd != previousFD {
			t.Fatal("test did not reuse descriptor")
		}
		previousFD = c.fd
		f.command("handshake %d", c.slot)
		if got, err := f.lookup(c).hostname(); got != want || err != nil || wireName(t, c) != want {
			t.Fatalf("reuse %d: %q, %v", i, got, err)
		}
		f.command("close %d", c.slot)
	}
	var reused int
	line := f.command("stats")
	if n, err := fmt.Sscanf(line, "stats %d", &reused); err != nil || n != 1 || reused == 0 {
		t.Fatalf("fixture did not demonstrate TLS object address reuse: %s", line)
	}
	t.Logf("verified %d TLS object address reuses", reused)
}

func TestVMUnsupported(t *testing.T) {
	for _, tc := range []struct {
		name, hostname, mode, op string
		absent                   bool
	}{
		{"memory-bio", "memory.test", "memory", "handshake", true},
		{"replaced-fd", "replaced.test", "fd", "badfd", true},
		{"no-name", "-", "fd", "handshake", false},
		{"invalid-name", "bad/name", "fd", "handshake", false},
		{"truncated-name", strings.Repeat("a", 255), "fd", "handshake", false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			f := newFixture(t, "tcp4")
			c := f.open(tc.hostname, "name-first", tc.mode)
			f.command("%s %d", tc.op, c.slot)
			if tc.op == "badfd" {
				f.command("handshake %d", c.slot)
			}
			if tc.absent {
				f.absent(c)
			} else if name, err := f.lookup(c).hostname(); err == nil {
				t.Fatalf("accepted %q", name)
			}
		})
	}
}

func TestVMRebind(t *testing.T) {
	f := newFixture(t, "tcp4")
	old := f.open("rebind.test", "name-first", "fd")
	c := f.accepted(f.command("rebind %d", old.slot))
	f.command("handshake %d", c.slot)
	f.absent(old)
	if got, err := f.lookup(c).hostname(); err != nil || got != "rebind.test" || wireName(t, c) != got {
		t.Fatalf("rebound name %q: %v", got, err)
	}
}

func TestVMFreshObservationInvalidatesOldSnapshot(t *testing.T) {
	f := newFixture(t, "tcp4")
	c := f.open("abandoned.test", "fd-first", "fd")
	f.command("fail %d", c.slot)
	if got, err := f.lookup(c).hostname(); got != "abandoned.test" || err != nil {
		t.Fatalf("failed setup name %q: %v", got, err)
	}
	f.command("replace %d -", c.slot)
	f.command("handshake %d", c.slot)
	if o := f.lookup(c); o.Len != 0 {
		t.Fatalf("stale name survived fresh unnamed observation: %+v", o)
	}
}

func TestVMMissedInitialObservation(t *testing.T) {
	f := newFixture(t, "tcp4")
	c := f.open("unknown.test", "fd-first", "fd")
	if err := f.probe.uprobe.Close(); err != nil {
		t.Fatal(err)
	}
	f.probe.uprobe = nil
	f.command("handshake %d", c.slot)
	f.absent(c)
	if got := wireName(t, c); got != "unknown.test" {
		t.Fatalf("TLS stopped working without observer: %q", got)
	}
}

// This test deliberately demonstrates why these snapshots MUST NOT feed a
// routing reader. A failed setup can publish a name without emitting a byte.
// If the next handshake entry is missed, the same live socket retains it.
func TestVMMissedObservationCounterexample(t *testing.T) {
	f := newFixture(t, "tcp4")
	c := f.open("abandoned.test", "fd-first", "fd")
	f.command("fail %d", c.slot)
	if got, err := f.lookup(c).hostname(); got != "abandoned.test" || err != nil {
		t.Fatalf("failed setup name %q: %v", got, err)
	}
	c.server.SetReadDeadline(time.Now().Add(50 * time.Millisecond))
	var b [1]byte
	if n, err := c.server.Read(b[:]); n != 0 || err == nil {
		t.Fatalf("failed setup emitted traffic: %d, %v", n, err)
	}
	f.command("replace %d actual.test", c.slot)
	if err := f.probe.uprobe.Close(); err != nil {
		t.Fatal(err)
	}
	f.probe.uprobe = nil // deliberately miss the next entry
	f.command("handshake %d", c.slot)
	wire := wireName(t, c)
	got, err := f.lookup(c).hostname()
	if err != nil || got != "abandoned.test" || wire != "actual.test" {
		t.Fatalf("counterexample not reproduced: snapshot %q, wire %q, error %v", got, wire, err)
	}
	t.Logf("unsafe snapshot reproduced: stored %q, actual ClientHello %q on the same live socket", got, wire)
}
